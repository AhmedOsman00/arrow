import Foundation
import SwiftBasicFormat
import SwiftSyntax
import SwiftSyntaxBuilder

/// Generates Swift source code for dependency registration using SwiftSyntaxBuilder.
///
/// This class builds a complete Swift source file containing:
/// - Import statements for all required modules
/// - A `DependencyRegistry` enum with a static `register(in:)` method
/// - Module instantiations
/// - Dependency registration calls in topological order
///
/// The generated code follows this structure (`public` is added in package mode).
/// `name:` is only emitted for `@Name`/`@Named` dependencies:
/// ```swift
/// // Generated by arrow. Do not edit.
///
/// import Arrow
///
/// enum AppDependencies: DependencyRegistry {
///   static func register(in container: Container) {
///     let module = Module()
///
///     container.register(Type.self, objectScope: .transient) { resolver in
///       module.provide(
///         resolver.resolve(B.self),
///         a: resolver.resolve(A.self),
///         c: resolver.resolve(C.self, name: "cType")
///       )
///     }
///   }
/// }
/// ```
class DependencyFile {
  /// The presenter providing UI models for code generation
  private let presenter: DependencyFilePresenting

  /// Initializes the code generator with a presenter
  ///
  /// - Parameter presenter: Presenter containing the file UI model
  init(presenter: DependencyFilePresenting) {
    self.presenter = presenter
  }

  private var model: FileUiModel { presenter.fileUiModel }

  /// The complete generated `dependencies.generated.swift` file, built lazily.
  ///
  /// Each piece is written as source text and parsed, then `BasicFormat` handles the indentation.
  lazy var file: SourceFileSyntax = {
    let source = SourceFileSyntax {
      for module in model.imports {
        DeclSyntax("import \(raw: module)")
      }
      for (module, condition) in model.conditionalImports.sorted(by: { $0.key < $1.key }) {
        conditional(.decl("import \(raw: module)"), on: condition)
      }
      registryDecl.with(\.leadingTrivia, .newlines(2))
    }
    return source.formatted(using: BasicFormat(indentationWidth: .spaces(2)))
      .cast(SourceFileSyntax.self)
      .with(\.leadingTrivia, .lineComment("// Generated by arrow. Do not edit.") + .newlines(2))
  }()

  /// Maps each module type name to the local variable that holds its instance.
  ///
  /// Names are lowerCamel (see `variableName(for:)`), keywords are escaped with backticks,
  /// and names that would collide get a numeric suffix.
  private lazy var moduleVariableNames: [String: String] = {
    var names = [String: String]()
    var used = Set<String>()
    for module in model.modules {
      let base = Self.variableName(for: module)
      var candidate = base
      var suffix = 2
      while used.contains(candidate) {
        candidate = "\(base)\(suffix)"
        suffix += 1
      }
      used.insert(candidate)
      names[module] = Self.reservedWords.contains(candidate) ? "`\(candidate)`" : candidate
    }
    return names
  }()

  /// ```swift
  /// enum AppDependencies: DependencyRegistry {
  ///   static func register(in container: Container) { ... }
  /// }
  /// ```
  /// A `@MainActor` module makes the registry `@MainActor`, so its factories can call the module's
  /// providers in Swift 6. `@preconcurrency` lets it still conform to the nonisolated protocol.
  private var registryDecl: DeclSyntax {
    let access = model.registry.isPublic ? "public " : ""
    let attributes = model.isMainActor ? "@MainActor\n" : ""
    let conformance = model.isMainActor ? "@preconcurrency DependencyRegistry" : "DependencyRegistry"
    let statements =
      model.modules.map { module in
        conditional(
          .decl("let \(raw: variableName(for: module)) = \(raw: module)()"),
          on: model.moduleConditions[module])
      }
      + model.dependencies.map { dependency in
        conditional(.expr(registration(dependency)), on: dependency.condition).with(\.leadingTrivia, .newlines(2))
      }
    return """
      \(raw: attributes)\(raw: access)enum \(raw: model.registry.name): \(raw: conformance) {
      \(raw: access)static func register(in container: Container) {
      \(CodeBlockItemListSyntax(statements))
      }
      }
      """
  }

  /// ```swift
  /// container.register(Type.self, name: "Primary", objectScope: .transient) { resolver in
  ///   module.provide(
  ///     resolver.resolve(B.self),
  ///     a: resolver.resolve(A.self),
  ///     c: resolver.resolve(C.self, name: "cType")
  ///   )
  /// }
  /// ```
  ///
  /// A `@MainActor` provider's factory first checks it's on the main thread. The container runs
  /// factories on whichever thread resolves, and nothing else stops a background resolve from
  /// building a main-actor object off the main thread.
  private func registration(_ dependency: DependencyUiModel) -> ExprSyntax {
    let name = dependency.name.map { ", name: \"\($0)\"" } ?? ""
    var provider = "\(variableName(for: dependency.module)).\(dependency.block)"
    if dependency.isFunc {
      let arguments = dependency.parameters.map { "\n" + argument($0) }.joined(separator: ",")
      provider += "(\(arguments)\(dependency.parameters.isEmpty ? "" : "\n"))"
    }
    if dependency.isMainActor {
      let message = "`\(dependency.type)` is created on the main actor, so resolve it on the main thread."
      provider = "precondition(Thread.isMainThread, \"\(message)\")\nreturn \(provider)"
    }
    return """
      container.register(\(raw: TypeName.metatypeExpression(dependency.type))\(raw: name), \
      objectScope: .\(raw: dependency.scope)) { resolver in
      \(raw: provider)
      }
      """
  }

  /// `c: resolver.resolve(C.self, name: "cType")`, or `tryResolve` for an optional parameter.
  ///
  /// Names are emitted as written: the parser keeps the literal's source text, escapes included.
  private func argument(_ parameter: DependencyUiModel.Parameter) -> String {
    let label = parameter.label.map { "\($0): " } ?? ""
    let method = parameter.isOptional ? "tryResolve" : "resolve"
    let name = parameter.id.map { ", name: \"\($0)\"" } ?? ""
    return "\(label)resolver.\(method)(\(TypeName.metatypeExpression(parameter.type))\(name))"
  }

  /// ```swift
  /// #if DEBUG
  /// item
  /// #endif
  /// ```
  private func conditional(_ item: CodeBlockItemSyntax.Item, on condition: String?) -> CodeBlockItemSyntax {
    let item = CodeBlockItemSyntax(item: item)
    guard let condition else { return item }
    return CodeBlockItemSyntax(item: .decl("#if \(raw: condition)\n\(item)\n#endif"))
  }
}

extension DependencyFile {
  private static let reservedWords: Set<String> = [
    "any", "as", "associatedtype", "break", "case", "catch", "class", "continue", "default",
    "defer", "deinit", "do", "else", "enum", "extension", "fallthrough", "false", "fileprivate",
    "for", "func", "guard", "if", "import", "in", "init", "inout", "internal", "is", "let", "nil",
    "open", "operator", "private", "protocol", "public", "repeat", "rethrows", "return", "self",
    "static", "struct", "subscript", "super", "switch", "throw", "throws", "true", "try",
    "typealias", "var", "where", "while",
  ]

  /// `MoreModule` -> `moreModule`, `URLModule` -> `urlModule`, `Foo.Bar` -> `foo_Bar`.
  static func variableName(for module: String) -> String {
    let identifier = module.replacingOccurrences(of: ".", with: "_")
    let characters = Array(identifier)
    let leadingUppercase = characters.prefix { $0.isUppercase }.count
    guard leadingUppercase > 0 else { return identifier }

    // Keep the last capital of an acronym when a lowercase word follows it (URLModule -> urlModule).
    let lowercasedCount =
      leadingUppercase > 1 && leadingUppercase < characters.count
      ? leadingUppercase - 1
      : leadingUppercase
    return String(characters[..<lowercasedCount]).lowercased()
      + String(characters[lowercasedCount...])
  }

  private func variableName(for module: String) -> String {
    moduleVariableNames[module] ?? Self.variableName(for: module)
  }
}
